// Decrypt only the local synthetic fixture emitted by HeadlessAuthProbe.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../../../package.json',import.meta.url));
const forge=require('node-forge');
await import('../../../src/seed.js');
const root=path.resolve(process.argv[2]||'');
if(!process.argv[2]||!root.includes('hira-headless-poc-'))throw Error('synthetic fixture directory required');
const read=n=>fs.readFileSync(path.join(root,n)).toString('binary');
const cert=forge.pki.certificateFromAsn1(forge.asn1.fromDer(read('signCert.der')));
assert.equal(cert.subject.getField('OU')?.value,'SYNTHETIC-ONLY');
const key=forge.pki.privateKeyFromAsn1(forge.asn1.fromDer(read('private.pk8')));
const top=forge.asn1.fromDer(read('request.cms'));
const oid=n=>forge.asn1.derToOid(n.value);
assert.equal(oid(top.value[0]),'1.2.840.113549.1.7.3');
const env=top.value[1].value[0];
const recipients=env.value.find(n=>n.tagClass===0&&n.type===17);
assert.equal(recipients.value.length,1);
const recipient=recipients.value[0];
assert.equal(oid(recipient.value[2].value[0]),'1.2.840.113549.1.1.1');
const seedKey=key.decrypt(recipient.value[3].value,'RSAES-PKCS1-V1_5');
const content=env.value[env.value.indexOf(recipients)+1];
assert.equal(oid(content.value[0]),'1.2.840.113549.1.7.1');
assert.equal(oid(content.value[1].value[0]),'1.2.410.200004.1.4');
const iv=content.value[1].value[1].value;
const bytes=n=>typeof n.value==='string'?n.value:n.value.map(bytes).join('');
const ciphertext=bytes(content.value[2]);
const d=forge.cipher.createDecipher('SEED-CBC',seedKey);d.start({iv});d.update(forge.util.createBuffer(ciphertext));
assert.ok(d.finish());assert.equal(d.output.getBytes(),read('request.bin'));
console.log('PASS existing Node SEED decrypts Java DDMD CMS envelope; serialized Credentials bytes match');
